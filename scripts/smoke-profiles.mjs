import { _electron as electron } from 'playwright';
import { resolve } from 'node:path';
import { mkdir, mkdtemp, readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
await mkdir('artifacts', { recursive: true });
const userData = await mkdtemp(resolve('artifacts/profiles-'));
const exportPath = resolve(userData, 'exported.json'), invalidPath = resolve(userData, 'invalid.json');
const legacy = { version: 1, theme: 'light', autoScroll: true, recent: [], profile: { exe: '', args: '--legacy', cwd: '', deviceRegion: { enabled: true, geoId: 94 }, language: { enabled: false, userUI: 'en-US', systemUI: 'en-US' }, locale: { enabled: false, user: 'en-US', system: 'en-US' } } };
await writeFile(resolve(userData, 'settings.json'), JSON.stringify(legacy));
const packaged = process.argv.includes('--packaged');
const options = packaged ? { executablePath: resolve('release/win-unpacked/Frida Region Launcher.exe'), args: [] } : { args: ['.'] };
const env = { ...process.env, FRL_TEST_USER_DATA: userData };
if (packaged) { env.PATH = resolve(process.env.SystemRoot, 'System32'); for (const name of ['PYTHONHOME','PYTHONPATH','VIRTUAL_ENV','NODE_PATH']) delete env[name]; }
let application = await electron.launch({ ...options, env });
try {
 const page = await application.firstWindow();
 const errors=[]; page.on('pageerror', e => errors.push(e.message));
 await page.getByRole('heading', {name:'在不同地区，自由运行。'}).waitFor();
 await page.getByRole('textbox',{name:'程序路径'}).fill(resolve('artifacts/compatibility/GeoTimeProbe.exe'));
 await page.getByRole('button',{name:'应用日本兼容预设',exact:true}).click();
 await page.getByRole('button',{name:'程序配置',exact:true}).click();
 await page.getByRole('textbox',{name:'新配置名称'}).fill('日本测试');
 await page.getByRole('button',{name:'新增配置',exact:true}).click();
 await page.getByRole('textbox',{name:'配置名称 日本测试',exact:true}).waitFor();
 assert.deepEqual(JSON.parse(await readFile(resolve(userData, 'settings.v1.backup.json'), 'utf8')), legacy);
 await page.getByRole('button',{name:'复制 日本测试',exact:true}).click();
 await page.getByRole('textbox',{name:'配置名称 日本测试 副本',exact:true}).fill('美国夏令时');
 await page.getByRole('button',{name:'保存名称 日本测试 副本',exact:true}).click();
 await page.getByRole('textbox',{name:'配置名称 美国夏令时',exact:true}).waitFor();
 const second = page.locator('.profile-card').filter({has:page.getByRole('textbox',{name:'配置名称 美国夏令时',exact:true})});
 await second.getByRole('button',{name:'编辑环境',exact:true}).click();
 await page.getByRole('combobox',{name:'模拟时区'}).selectOption('Pacific Standard Time');
 await page.getByRole('combobox',{name:'用户地区预设'}).selectOption('244');
 await page.getByRole('button',{name:'程序配置',exact:true}).click();
 await application.evaluate(({dialog}, path) => { dialog.showSaveDialog=async()=>({canceled:false,filePath:path}); },exportPath);
 await page.getByRole('button',{name:'导出全部',exact:true}).click();
 await page.waitForFunction(async () => !(document.querySelector('button[aria-label="复制 日本测试"]')?.disabled));
 let exported;
 for(let i=0;i<30;i++){try{exported=JSON.parse(await readFile(exportPath,'utf8'));break;}catch{await new Promise(r=>setTimeout(r,100));}}
 assert.equal(exported.profiles.length,2); assert.equal(exported.profiles[1].config.geoRegion.geoId,244);
 assert.equal(exported.profiles[0].config.timezone.key,'Tokyo Standard Time');
 await application.evaluate(({dialog},path)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[path]});},exportPath);
 await page.getByRole('button',{name:'导入配置',exact:true}).click();
 await page.getByText('4 / 100 个配置',{exact:true}).waitFor();
 const saved=await page.evaluate(()=>window.launcher.load());
 assert.equal(new Set(saved.profiles.map(p=>p.id)).size,4);
 assert.equal(saved.profiles[2].config.timezone.key,'Tokyo Standard Time');
 assert.ok(!['running','initializing'].includes((await page.evaluate(()=>window.launcher.command('get_status'))).payload?.state));
 await writeFile(invalidPath,JSON.stringify({...exported,version:999}));
 await application.evaluate(({dialog},path)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[path]});},invalidPath);
 await page.getByRole('button',{name:'导入配置',exact:true}).click();
 await page.getByRole('alert').waitFor();
 assert.equal((await page.evaluate(()=>window.launcher.load())).profiles.length,4);
 await page.getByRole('button',{name:'删除 日本测试',exact:true}).first().click();
 await page.getByRole('button',{name:'确认删除配置',exact:true}).click();
 await page.getByText('3 / 100 个配置',{exact:true}).waitFor();
 await page.screenshot({path:'artifacts/ui-profiles.png',fullPage:true});
 await application.close();
 application=await electron.launch({...options,env});
 const reopened=await application.firstWindow();
 await reopened.getByRole('button',{name:'程序配置',exact:true}).click();
 await reopened.getByText('3 / 100 个配置',{exact:true}).waitFor();
 await reopened.getByRole('button',{name:'启动此配置',exact:true}).first().click();
 await reopened.getByText('程序已退出',{exact:true}).waitFor({timeout:20000});
 await reopened.getByRole('button',{name:/运行日志/}).first().click();
 await reopened.getByText('GetUserGeoID',{exact:true}).first().waitFor();
 assert.equal(await reopened.locator('.log-level.ERROR').count(),0);
 assert.deepEqual(errors,[]);
 console.log('PASS: actual Electron profile create/copy/rename/edit/switch/import/export/delete/restart/launch; import IDs renewed; invalid import rejected; real GeoID hooks');
} finally { await application.close(); }
